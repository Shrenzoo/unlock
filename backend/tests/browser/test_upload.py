"""Package import through the browser: genuine upload and rejected packages.

The genuine upload uses a supported synthetic STEP and manifest generated by the
repository's fixture tool under a new project id, so it is a real import, not one
of the projects bundled at start-up. No arbitrary industrial assembly is implied.
"""

from __future__ import annotations

import json
import time

import pytest
from browser_harness import new_page, report, shot

pytestmark = pytest.mark.browser


def upload(page, files):
    page.locator('input[type="file"]').set_input_files(files)


def as_file(name, data: bytes, mime="application/octet-stream"):
    return dict(name=name, mimeType=mime, buffer=data)


@pytest.fixture(scope="module")
def generated_package(tmp_path_factory):
    from unlock_engine.fixtures import generate_fixture

    source = generate_fixture(tmp_path_factory.mktemp("upload") / "B01", "B01")
    manifest = json.loads((source / "manifest.json").read_text())
    manifest["project_id"] = f"upload_b01_{int(time.time())}"
    return dict(step=(source / "assembly.step").read_bytes(), manifest=manifest)


def test_genuine_step_and_manifest_upload_renders_the_imported_revision(
    browser, stack, generated_package, evidence_dir
):
    context, page, monitor = new_page(browser, stack.api)
    before = {p["id"] for p in stack.get("/v1/projects")}
    pid = generated_package["manifest"]["project_id"]
    assert pid not in before
    page.goto(stack.web + "/projects")
    page.get_by_role("link", name="Open", exact=True).first.wait_for()
    started = time.monotonic()
    with page.expect_response(
        lambda r: r.request.method == "POST" and r.url.endswith("/imports")
    ) as posted:
        upload(
            page,
            [
                as_file("assembly.step", generated_package["step"], "model/step"),
                as_file(
                    "manifest.json",
                    json.dumps(generated_package["manifest"]).encode(),
                    "application/json",
                ),
            ],
        )
    assert posted.value.status == 202
    page.wait_for_url(f"**/projects/{pid}", timeout=180_000)
    components = [c["id"] for c in generated_package["manifest"]["components"]]
    page.locator(f'[role="treeitem"][data-id="{components[0]}"]').wait_for()
    page.wait_for_timeout(800)
    report["measurements"]["upload_to_workspace_s"] = round(
        time.monotonic() - started, 2
    )

    revision = stack.latest_revision(pid)
    tree = page.locator('[role="treeitem"]').evaluate_all(
        "items => items.map(i => i.dataset.id)"
    )
    assert sorted(tree) == sorted(components)
    assert page.locator(".topbar__rev").inner_text() == revision["label"]
    viewer = page.locator('[data-geometry-source="backend-brep"]')
    assert viewer.get_attribute("data-preview-id") == revision["preview_artifact_id"]

    # The coordinator's revision equals an independent import of the same bytes.
    from unlock_engine.package import load_files
    from unlock_engine.worker import isolated_import

    independent = isolated_import(
        load_files(
            {
                "assembly.step": generated_package["step"],
                "manifest.json": json.dumps(generated_package["manifest"]).encode(),
            }
        )
    )
    assert revision["input_hash"] == independent["input_hash"]
    preview = json.loads(stack.raw(f"/v1/artifacts/{revision['preview_artifact_id']}"))
    assert sorted(c["occurrence_id"] for c in preview["components"]) == sorted(
        components
    )
    listed = {p["id"]: p for p in stack.get("/v1/projects")}
    assert listed[pid]["status"] == "ready" and set(listed) == before | {pid}
    shot(page, "upload-imported-workspace")
    report["correlation"]["upload"] = dict(
        project_id=pid,
        revision_id=revision["id"],
        input_hash=revision["input_hash"],
        geometry_hash=independent["geometry_hash"],
        components=len(components),
    )
    problems = monitor.problems()
    assert problems == dict(console=[], page=[], failed=[], http=[]), problems
    context.close()


@pytest.mark.parametrize(
    "case",
    ["mesh-file", "geometry-without-manifest", "unparseable-step", "invalid-manifest"],
)
def test_invalid_packages_are_rejected_without_creating_projects(
    browser, stack, generated_package, case
):
    context, page, monitor = new_page(browser, stack.api)
    before = stack.get("/v1/projects")
    page.goto(stack.web + "/projects")
    page.get_by_role("link", name="Open", exact=True).first.wait_for()
    manifest = dict(
        generated_package["manifest"], project_id=f"rejected_{case.replace('-', '_')}"
    )
    files = {
        "mesh-file": [as_file("bracket.stl", b"solid x\nendsolid x\n")],
        "geometry-without-manifest": [
            as_file("assembly.step", generated_package["step"])
        ],
        "unparseable-step": [
            as_file("assembly.step", b"ISO-10303-21;\nthis is not a STEP body\n"),
            as_file("manifest.json", json.dumps(manifest).encode()),
        ],
        "invalid-manifest": [
            as_file("assembly.step", generated_package["step"]),
            as_file("manifest.json", b'{"project_id": "x", "components": "nope"}'),
        ],
    }[case]
    upload(page, files)
    alert = page.get_by_role("alert").filter(has_text="Package not accepted")
    alert.wait_for(timeout=120_000)
    assert alert.inner_text().strip()
    page.wait_for_timeout(2500)  # one dashboard refresh cycle
    after = stack.get("/v1/projects")
    assert [p["id"] for p in after] == [p["id"] for p in before], (
        "no project may be created"
    )
    assert page.url.rstrip("/").endswith("/projects"), "the user stays on Projects"
    client_side = case in ("mesh-file", "geometry-without-manifest")
    posted = [c for c in monitor.api_calls if c["path"].endswith("/imports")]
    assert (not posted) if client_side else posted, "client checks run before upload"
    report["correlation"].setdefault("rejected_packages", {})[case] = (
        alert.inner_text()[:300]
    )
    context.close()
